class _Stash:
    """Временные заглушки для того, что нельзя размечать (код, URL, email)."""

    def __init__(self) -> None:
        self._items: list[str] = []

    def __call__(self, match: "re.Match[str]") -> str:
        if len(self._items) >= _PUA_LIMIT - _PUA_BASE:
            return match.group(0)
        self._items.append(match.group(0))
        return _PUA_OPEN + chr(_PUA_BASE + len(self._items) - 1) + _PUA_CLOSE

    def restore(self, text: str) -> str:
        def replace(match: "re.Match[str]") -> str:
            index = ord(match.group(1)) - _PUA_BASE
            if 0 <= index < len(self._items):
                return self._items[index]
            return match.group(0)

        return _PLACEHOLDER_RE.sub(replace, text)


def _apply_markup(word: str, markup: str) -> str:
    """Вставить ``+`` в исходное слово по позициям разметки (регистр цел)."""
    positions: list[int] = []
    shift = 0
    for index, char in enumerate(markup):
        if char == STRESS_MARK:
            positions.append(index - shift)
            shift += 1
    result = word
    for position in reversed(positions):
        result = result[:position] + STRESS_MARK + result[position:]
    return result


def _mark_match(match: "re.Match[str]", entries: Mapping[str, str]) -> str:
    """Разметить одно найденное слово, если оно есть в словаре."""
    word = match.group(0)
    start, end = match.span()
    text = match.string
    # Уже размеченное слово: соседний '+' — признак чужой разметки, второй не
    # ставим (идемпотентность на любом тексте, включая частичный прогон).
    if (start > 0 and text[start - 1] == STRESS_MARK) or (
        end < len(text) and text[end] == STRESS_MARK
    ):
        return word
    markup = entries.get(word.lower())
    if markup is None:
        return word
    return _apply_markup(word, markup)


def apply_stress(
    text: object,
    *,
    env: Mapping[str, str] | None = None,
    dictionary: Mapping[str, str] | None = None,
) -> str:
    """Расставить ``+`` перед ударными гласными для Silero v4_ru.

    Текст для ответа пользователю не меняется — функцию зовёт только синтез
    (``eva/tts.py``, ``SileroTTS._prepare_text``). ``EVA_STRESS=0``
    возвращает текст как есть. ``dictionary`` подменяет словарь (тесты).
    """
    value = "" if text is None else str(text)
    if not value or not stress_enabled(env):
        return value
    entries = dict(dictionary) if dictionary is not None else stress_dictionary(
        env=env
    )
    if not entries:
        return value
    stash = _Stash()
    protected = _CODE_SPAN_RE.sub(stash, value)
    protected = _URL_RE.sub(stash, protected)
    protected = _EMAIL_RE.sub(stash, protected)
    marked = _WORD_RE.sub(lambda match: _mark_match(match, entries), protected)
    return stash.restore(marked)


# Словарь читается при старте (файл маленький) и дальше живёт в кэше: первая
# фраза не должна платить за чтение, а битая строка видна в логе сразу.
try:  # pragma: no cover - ветка на случай нечитаемого файла
    stress_dictionary()
except Exception as exc:  # noqa: BLE001 - словарь не должен мешать импорту
    logger.warning("ударения: словарь не прочитан при старте: %s", exc)
