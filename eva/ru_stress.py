# --------------------------------------------------------------------------- #
# сборка и проверка словаря
# --------------------------------------------------------------------------- #
def _entry_markup(stem: str, tail: str) -> str:
    """Собрать разметку статьи: ``основа + "+" + ударная часть``.

    Если ударная часть уже размечена (два ударения в композите вида
    «Баба-Яга»), лишний ``+`` не добавляется.
    """
    if STRESS_MARK in tail:
        return f"{stem}{tail}"
    return f"{stem}{STRESS_MARK}{tail}"


def _validate(word: str, markup: str) -> str | None:
    """Проверить статью; вернуть причину или ``None``, если всё в порядке."""
    if not word:
        return "пустое слово"
    if not markup:
        return "пустая разметка"
    if re.search(r"\s", word) or re.search(r"\s", markup):
        return "пробелы внутри слова или разметки"
    if not re.fullmatch(r"[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*", word):
        return "слово должно состоять из русских букв (дефис допустим)"
    if len(word.replace("-", "")) < 2:
        return "слово короче двух букв"
    if STRESS_MARK not in markup:
        return "нет знака ударения '+'"
    if STRESS_MARK * 2 in markup:
        return "два '+' подряд"
    if markup.replace(STRESS_MARK, "").lower() != word.lower():
        return f"разметка {markup!r} не совпадает со словом {word!r}"
    for index, char in enumerate(markup):
        if char != STRESS_MARK:
            continue
        following = markup[index + 1] if index + 1 < len(markup) else ""
        if following.lower() not in _VOWELS:
            return f"'+' перед {following!r} — знак ставится только перед гласной"
    return None


def _build_builtin() -> dict[str, str]:
    """Построить встроенный словарь; ошибка в статье — падение на импорте."""
    entries: dict[str, str] = {}
    for word, stem, tail in _BUILTIN_SPEC:
        markup = _entry_markup(stem, tail)
        problem = _validate(word, markup)
        if problem is not None:
            raise ValueError(
                f"словарь ударений: {word!r} → {markup!r}: {problem}"
            )
        entries[word.lower()] = markup
    return entries


_BUILTIN: dict[str, str] = _build_builtin()


def builtin_stress_dictionary() -> dict[str, str]:
    """Копия встроенного словаря (слово в нижнем регистре → разметка)."""
    return dict(_BUILTIN)


# --------------------------------------------------------------------------- #
# файл словаря и кэш
# --------------------------------------------------------------------------- #
def _env(env: Mapping[str, str] | None, name: str) -> str | None:
    source: Mapping[str, str] = os.environ if env is None else env
    raw = source.get(name)
    text = str(raw).strip() if raw is not None else ""
    return text or None


def stress_enabled(env: Mapping[str, str] | None = None) -> bool:
    """Не отключена ли расстановка ударений (``EVA_STRESS=0`` — выкл.)."""
    raw = _env(env, "EVA_STRESS")
    if raw is None:
        return True
    return raw.lower() not in ("0", "false", "no", "off", "нет", "выкл")


def _stress_path(env: Mapping[str, str] | None) -> Path:
    raw = _env(env, "EVA_STRESS_FILE")
    return Path(raw).expanduser() if raw else DEFAULT_STRESS_FILE


def _file_signature(path: Path) -> tuple[str, int | None, int]:
    """Отпечаток файла: путь, mtime и размер (кэш живёт до изменения)."""
    try:
        stat = path.stat()
    except OSError:
        return (str(path), None, 0)
    return (str(path), stat.st_mtime_ns, stat.st_size)


def load_stress_file(path: str | Path | None = None) -> dict[str, str]:
    """Прочитать внешний словарь ``слово<TAB>разметка``.

    Битая строка (нет таба, пустая разметка, разметка не совпадает со словом,
    ``+`` не перед гласной) даёт предупреждение с номером строки и
    пропускается: словарь не должен ронять синтез. Отсутствующий файл — не
    ошибка: работает только встроенный словарь.
    """
    target = Path(path) if path is not None else DEFAULT_STRESS_FILE
    try:
        content = target.read_text(encoding="utf-8")
    except OSError as exc:
        logger.info(
            "ударения: внешний словарь %s не прочитан (%s) — только встроенный",
            target,
            exc,
        )
        return {}

    entries: dict[str, str] = {}
    for number, raw in enumerate(content.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "\t" not in line:
            logger.warning(
                "ударения: %s:%d: нет TAB между словом и разметкой — "
                "строка пропущена: %r",
                target,
                number,
                raw,
            )
            continue
        word, _, markup = line.partition("\t")
        word, markup = word.strip(), markup.strip()
        problem = _validate(word, markup)
        if problem is not None:
            logger.warning(
                "ударения: %s:%d: %s — строка пропущена: %r",
                target,
                number,
                problem,
                raw,
            )
            continue
        entries[word.lower()] = markup
    return entries


_CACHE: dict[str, str] | None = None
_CACHE_SIGNATURE: tuple[str, int | None, int] | None = None


def stress_dictionary(
    *,
    env: Mapping[str, str] | None = None,
    refresh: bool = False,
) -> dict[str, str]:
    """Словарь ударений: встроенный + ``data/stress.txt``, с кэшем.

    Читается один раз; если файл изменился (mtime/размер), кэш обновляется.
    Внешние записи перекрывают встроенные.
    """
    global _CACHE, _CACHE_SIGNATURE
    path = _stress_path(env)
    signature = _file_signature(path)
    if not refresh and _CACHE is not None and _CACHE_SIGNATURE == signature:
        return _CACHE
    merged = dict(_BUILTIN)
    merged.update(load_stress_file(path))
    _CACHE = merged
    _CACHE_SIGNATURE = signature
    return merged


