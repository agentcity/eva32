"""Ударения для Silero: знак ``+`` перед ударной гласной (задача 0222).

Silero v4_ru понимает знак ударения ``+`` перед ударной гласной:
``"Колоб+ок"`` звучит как Колобо́к. Без разметки модель ставит ударение по
общим правилам и ошибается на сказочных словах и именах: Ко́лобок вместо
Колобо́к, Жу́равль вместо Жура́вль, Тере́мок вместо Теремо́к. Достаточно
расставить ``+`` **перед синтезом** — в тексте ответа пользователю плюсов нет
(см. ``eva/tts.py``, хук ``SileroTTS._prepare_text``).

Публичная функция — :func:`apply_stress`. Словарь состоит из двух частей:

* встроенный (``_BUILTIN_SPEC``) — сказочная лексика и частые слова, где
  Silero ошибается; статья хранится как «слово, основа, ударная часть», а
  разметка собирается как ``основа + "+" + ударная часть``;
* внешний ``data/stress.txt`` — расширяемый словарь, строка
  ``слово<TAB>разметка`` (``Колобок\tКолоб+ок``). Файл читается один раз и
  кэшируется; битая строка даёт понятное предупреждение в лог и пропускается,
  а не роняет синтез. Внешние записи перекрывают встроенные — так можно
  поправить ударение без правки кода.

Примеры::

    >>> apply_stress("Колобок и Теремок")
    'Колоб+ок и Терем+ок'
    >>> apply_stress("Колобка позвал Журавль")
    'Колобк+а позвал Жур+авль'
    >>> apply_stress("Б+аба-Яг+а")
    'Б+аба-Яг+а'

Сохраняются регистр (``КОЛОБОК`` → ``КОЛОБ+ОК``), пунктуация и пробелы.
Функция идемпотентна: уже размеченное слово не получает второй ``+``.
Не трогаются слова короче двух букв, латиница, числа, код в бэктиках, URL и
email. Отключается переменной ``EVA_STRESS=0`` (A/B и откат).
"""

